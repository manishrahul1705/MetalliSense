const assert = require('node:assert/strict');
const { initTestDb, store, getDb, closeDb, testDbPath } = require('./testHelper');
const dri = require('../driQa');
const maker = { userId: 'QA-MAKER', username: 'maker', displayName: 'QA Maker' };
const checker = { userId: 'QA-CHECKER', username: 'checker', displayName: 'QA Checker' };
const values = { feTotal: 92, feMetallic: 85, C: 1.2, P: 0.03, S: 0.02, moisture: 1 };
initTestDb();
const lot = store.addLot({ materialType: 'DRI', receivedKg: 1000, supplier: 'Stage1 test supplier' }, maker.displayName);
const first = dri.enter(lot.lotId, values, maker);
assert.throws(() => dri.approve(first.qaId, {}, maker), { status: 403 });
assert.throws(() => dri.approve(first.qaId, {}, { ...maker, displayName: 'Renamed maker' }), { status: 403 });
getDb().exec("CREATE TRIGGER fail_qa_review BEFORE INSERT ON maker_checker_reviews BEGIN SELECT RAISE(ABORT, 'injected audit failure'); END;");
assert.throws(() => dri.approve(first.qaId, {}, checker), /injected audit failure/);
assert.equal(store.qa.get(first.qaId).status, 'PENDING_APPROVAL');
assert.equal(store.getLot(lot.lotId).chemistrySource, lot.chemistrySource);
getDb().exec('DROP TRIGGER fail_qa_review');
const approved = dri.approve(first.qaId, {}, checker);
assert.equal(approved.qa.approvedById, checker.userId);
assert.equal(store.qa.get(first.qaId).status, 'APPROVED', 'approval must persist');
assert.equal(store.getLot(lot.lotId).chemistrySource, 'LAB', 'chemistry source must persist');
assert.equal(store.getLot(lot.lotId).tested.feTotal, values.feTotal);
assert.equal(store.qa.get(first.qaId).analystId, maker.userId);
const review = getDb().prepare('SELECT * FROM maker_checker_reviews WHERE entity_id = ? AND is_superseded = 0').get(first.qaId);
assert.equal(review.maker_id, maker.userId);
assert.equal(review.checker_id, checker.userId);
assert.equal(review.entity_version, first.version);
assert.throws(() => dri.approve(first.qaId, {}, checker), { status: 409 });
assert.equal(getDb().prepare('SELECT count(*) AS count FROM maker_checker_reviews WHERE entity_id = ?').get(first.qaId).count, 1);
const second = dri.enter(lot.lotId, values, maker);
const third = dri.enter(lot.lotId, values, maker);
assert.equal(second.version, 2);
assert.equal(third.version, 3);
assert.equal(store.qa.get(second.qaId).status, 'SUPERSEDED');
assert.throws(() => dri.approve(second.qaId, {}, checker), { status: 409 });
assert.throws(() => dri.reject(third.qaId, { reason: 'Retest' }, maker), { status: 403 });
dri.reject(third.qaId, { reason: 'Retest' }, checker);
assert.equal(store.qa.get(third.qaId).status, 'REJECTED');
assert.equal(store.qa.get(third.qaId).rejectedBy, checker.displayName);
assert.ok(store.qa.get(third.qaId).rejectedAt);
assert.throws(() => dri.reject(third.qaId, { reason: 'Retest' }, checker), { status: 409 });
closeDb();
require('../db').initDb(testDbPath);
assert.equal(store.qa.get(first.qaId).status, 'APPROVED');
assert.equal(store.qa.get(third.qaId).status, 'REJECTED');
assert.equal(store.getLot(lot.lotId).chemistrySource, 'LAB');
closeDb();
console.log('PASS: DRI durable approval/rejection, identity, versions, replay and reopen');
